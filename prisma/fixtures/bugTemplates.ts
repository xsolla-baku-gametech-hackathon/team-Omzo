/**
 * The seed corpus: fourteen bugs in one build, as ~380 reports.
 *
 * These are written by hand, one at a time, because the fixture is the demo.
 * Mechanically generated variations ("bug A occurrence 12") cluster perfectly
 * and prove nothing -- real testers write in their own register, drop the
 * subject, misspell things, hedge, and describe a crash without ever using
 * the word. If the engine only survives tidy input, it does not work.
 *
 * Scenes are the strongest separator (a different scene is a veto, §5.2 B),
 * so two bugs sharing a scene are given genuinely different vocabulary --
 * that is the case worth testing, not two bugs a world apart.
 */

export interface BugTemplate {
  /** Stable key, used by tests to assert what collapsed into what. */
  readonly key: string;
  readonly scene: string;
  readonly centre: readonly [number, number, number];
  /** World units of jitter around the centre. */
  readonly spread: number;
  /**
   * Error lines this bug leaves behind. `{n}` becomes a varying number and
   * `{id}` a varying cuid, so the signature stripper is genuinely exercised
   * rather than handed identical strings.
   */
  readonly errorLines: readonly string[];
  /** Share of reports whose console actually caught the error. */
  readonly errorRate: number;
  /** GPU family this bug favours, if it favours one. */
  readonly gpuSkew?: string;
  readonly paraphrases: readonly string[];
}

